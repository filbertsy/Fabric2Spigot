package dev.fabric2spigot.generation;

import com.google.gson.Gson;
import com.google.gson.GsonBuilder;
import dev.fabric2spigot.analysis.FeatureDetector.Feature;
import dev.fabric2spigot.translation.TranslationRegistry.Translation;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

public final class ProjectGenerator {

    private final Gson gson = new GsonBuilder()
        .setPrettyPrinting()
        .create();

    public void generate(
        Path output,
        Map<String, Object> metadata,
        List<Feature> features,
        List<Translation> translations
    ) throws IOException {

        String modName = String.valueOf(metadata.get("name"));
        String modId = sanitize(String.valueOf(metadata.get("id")));

        Path project = output.resolve(modId + "-paper-project");

        Path javaDirectory = project.resolve(
            "src/main/java/dev/fabric2spigot/generated"
        );

        Path resources = project.resolve("src/main/resources");

        Files.createDirectories(javaDirectory);
        Files.createDirectories(resources);

        write(project.resolve("settings.gradle"),
            "rootProject.name = '" + modId + "-paper'\n");

        write(project.resolve("build.gradle"), """
            plugins {
                id 'java'
            }

            group = 'dev.fabric2spigot.generated'
            version = '0.1.0'

            repositories {
                mavenCentral()
                maven {
                    name = 'papermc'
                    url = 'https://repo.papermc.io/repository/maven-public/'
                }
            }

            dependencies {
                compileOnly 'io.papermc.paper:paper-api:1.21.8-R0.1-SNAPSHOT'
            }

            java {
                toolchain {
                    languageVersion = JavaLanguageVersion.of(21)
                }
            }

            tasks.withType(JavaCompile).configureEach {
                options.encoding = 'UTF-8'
            }
            """);

        String pluginClass = """
            package dev.fabric2spigot.generated;

            import org.bukkit.plugin.java.JavaPlugin;

            public final class GeneratedPlugin extends JavaPlugin {

                @Override
                public void onEnable() {
                    getLogger().info("Generated plugin initialized.");
                    getLogger().info("Original mod: %s");
                    getLogger().warning(
                        "This is an experimental scaffold. " +
                        "Fabric behavior has not been automatically reproduced."
                    );
                }

                @Override
                public void onDisable() {
                    getLogger().info("Generated plugin disabled.");
                }
            }
            """.formatted(javaString(modName));

        write(javaDirectory.resolve("GeneratedPlugin.java"), pluginClass);

        write(resources.resolve("plugin.yml"), """
            name: %s
            version: 0.1.0
            main: dev.fabric2spigot.generated.GeneratedPlugin
            api-version: '1.21'
            description: Experimental Paper port scaffold for %s
            """.formatted(modId, yamlString(modName)));

        Map<String, Object> report = new LinkedHashMap<>();

        report.put("engine", "Fabric2Spigot");
        report.put("engineVersion", "0.1.0");
        report.put("mode", "experimental");
        report.put("originalMod", metadata);
        report.put("features", features);
        report.put("translations", translations);
        report.put("generatedPlugin", "scaffold-only");
        report.put("behaviorAutomaticallyPorted", false);

        write(
            project.resolve("conversion-report.json"),
            gson.toJson(report)
        );

        write(
            project.resolve("diagnostics.md"),
            diagnostics(metadata, features, translations)
        );

        write(
            project.resolve("README.md"),
            """
            # %s — experimental Paper project

            Generated by Fabric2Spigot.

            ## Build

            Requires Java 21 and Gradle.

            Run:

            ```bash
            gradle build
            ```

            The output JAR will be inside `build/libs/`.

            ## Important

            This is an experimental plugin scaffold, not a completed
            behavioral port. Review `diagnostics.md` and implement
            the detected features before deploying it to a server.

            Do not install an unreviewed generated plugin on a production server.
            """.formatted(modName)
        );
    }

    private String diagnostics(
        Map<String, Object> metadata,
        List<Feature> features,
        List<Translation> translations
    ) {
        StringBuilder text = new StringBuilder();

        text.append("# Fabric2Spigot diagnostics\n\n");
        text.append("## Original mod\n\n");
        text.append("- Name: ").append(metadata.get("name")).append("\n");
        text.append("- ID: ").append(metadata.get("id")).append("\n");
        text.append("- Version: ").append(metadata.get("version")).append("\n");
        text.append("\n## Detected features\n\n");

        if (features.isEmpty()) {
            text.append("No recognized features detected.\n");
        }

        for (Feature feature : features) {
            text.append("- **")
                .append(feature.category())
                .append("** — ")
                .append(feature.source())
                .append(" — ")
                .append(feature.evidence())
                .append(" (")
                .append(feature.confidence())
                .append(" confidence)\n");
        }

        text.append("\n## Translation attempts\n\n");

        for (Translation item : translations) {
            text.append("- **")
                .append(item.category())
                .append("** — ")
                .append(item.status())
                .append("\n  - Target: ")
                .append(item.target().isBlank() ? "None" : item.target())
                .append("\n  - ")
                .append(item.message())
                .append("\n");
        }

        text.append("\n## Result\n\n");
        text.append("Generated project is a plugin scaffold. ");
        text.append("No original Fabric behavior has been automatically ");
        text.append("reproduced by this initial engine version.\n");

        return text.toString();
    }

    private void write(Path path, String content) throws IOException {
        Files.createDirectories(path.getParent());
        Files.writeString(path, content, StandardCharsets.UTF_8);
    }

    private String sanitize(String value) {
        String result = value.toLowerCase()
            .replaceAll("[^a-z0-9_-]", "-")
            .replaceAll("-+", "-");

        if (result.isBlank() || !Character.isLetter(result.charAt(0))) {
            return "converted-mod";
        }

        return result;
    }

    private String javaString(String value) {
        return value
            .replace("\\", "\\\\")
            .replace("\"", "\\\"")
            .replace("\n", "\\n")
            .replace("\r", "\\r");
    }

    private String yamlString(String value) {
        return value
            .replace("\\", "\\\\")
            .replace("'", "''")
            .replace("\n", " ");
    }
}
